// ============================================================
// G 函数（32 位输入/输出；X3 为最高字节）
// ============================================================
const M0 = 0xFC, M1 = 0xF3, M2 = 0xCF, M3 = 0x3F;
function seedG(x) {
  const x0 = (x >>> 0) & 0xff;         // X0 = 最低字节
  const x1 = (x >>> 8) & 0xff;
  const x2 = (x >>> 16) & 0xff;
  const x3 = (x >>> 24) & 0xff;
  const a = S0[x0], b = S1[x1], c = S0[x2], d = S1[x3];
  const z0 = ((a & M0) ^ (b & M1) ^ (c & M2) ^ (d & M3));
  const z1 = ((a & M1) ^ (b & M2) ^ (c & M3) ^ (d & M0));
  const z2 = ((a & M2) ^ (b & M3) ^ (c & M0) ^ (d & M1));
  const z3 = ((a & M3) ^ (b & M0) ^ (c & M1) ^ (d & M2));
  return ((z3 << 24) | (z2 << 16) | (z1 << 8) | z0) >>> 0;
}

// ============================================================
// 轮函数 F(Ki0,Ki1)(R) → (R0',R1')，RFC 4269 §2.1
// ============================================================
function seedF(r0, r1, k0, k1) {
  const a = (r0 ^ k0) >>> 0;
  const b = (r1 ^ k1) >>> 0;
  const t = (a ^ b) >>> 0;
  const gt = seedG(t);                        // G(t)
  const X = seedG((gt + a) >>> 0);            // X = G[G(t)+a]
  const inner = seedG((X + gt) >>> 0);        // G[X + G(t)]
  const r1p = inner;                          // R1' = G[X+G(t)]
  const r0p = ((inner + X) >>> 0);            // R0' = G[X+G(t)] + X
  return [r0p, r1p];
}

