// 密钥调度 → 16 组 (Ki0,Ki1)
// ============================================================
const KC = [
  0x9E3779B9,0x3C6EF373,0x78DDE6E6,0xF1BBCDCC,
  0xE3779B99,0xC6EF3733,0x8DDE6E67,0x1BBCDCCF,
  0x3779B99E,0x6EF3733C,0xDDE6E678,0xBBCDCCF1,
  0x779B99E3,0xEF3733C6,0xDE6E678D,0xBCDCCF1B,
];
function seedKeySchedule(keyHex) {
  const c = keyHex.replace(/[^0-9a-fA-F]/g, "");
  if (c.length !== 32) throw new Error("SEED 密钥须为 128 位（32 hex 字符）");
  let k0 = parseInt(c.substr(0, 8), 16) >>> 0;
  let k1 = parseInt(c.substr(8, 8), 16) >>> 0;
  let k2 = parseInt(c.substr(16, 8), 16) >>> 0;
  let k3 = parseInt(c.substr(24, 8), 16) >>> 0;
  const rks = [];
  for (let i = 0; i < 16; i++) {
    const ki0 = seedG(((k0 + k2 - KC[i]) >>> 0));
    const ki1 = seedG(((k1 - k3 + KC[i]) >>> 0));
    rks.push([ki0, ki1]);
    if (i % 2 === 0) { // 奇数轮（i 从 0 起）：Key0||Key1 右旋 8 位
      const t = k0;
      k0 = ((k0 >>> 8) | (k1 << 24)) >>> 0;
      k1 = ((k1 >>> 8) | (t << 24)) >>> 0;
    } else {           // 偶数轮：Key2||Key3 左旋 8 位
      const t = k2;
      k2 = ((k2 << 8) | (k3 >>> 24)) >>> 0;
      k3 = ((k3 << 8) | (t >>> 24)) >>> 0;
    }
  }
  return rks;
}

// ============================================================
// Feistel 16 轮（L、R 各为 64 位 = [hi32, lo32]）
// ============================================================
function seedCryptBlock(Lh, Ll, Rh, Rl, rks, decrypt) {
  const keys = decrypt ? [...rks].reverse() : rks;
  let l0 = Lh >>> 0, l1 = Ll >>> 0, r0 = Rh >>> 0, r1 = Rl >>> 0;
  for (let i = 0; i < 15; i++) {
    const [f0, f1] = seedF(r0, r1, keys[i][0], keys[i][1]);
    const t0 = r0, t1 = r1;
    r0 = (l0 ^ f0) >>> 0;
    r1 = (l1 ^ f1) >>> 0;
    l0 = t0;
    l1 = t1;
  }
  const [f0, f1] = seedF(r0, r1, keys[15][0], keys[15][1]);
  l0 = (l0 ^ f0) >>> 0;
  l1 = (l1 ^ f1) >>> 0;
  return [l0, l1, r0, r1];
}

const u32 = (x) => x.toString(16).padStart(8, "0");
function seedCrypt(text, p, decrypt) {
  const rks = seedKeySchedule(String((p && p.key) || ""));
  const inHex = String(text || "").replace(/[^0-9a-fA-F]/g, "");
  if (inHex.length === 0 || inHex.length % 32 !== 0) throw new Error("输入须为 16 字节（32 hex）的整数倍，ECB 不自动填充");
  let out = "";
  for (let off = 0; off < inHex.length; off += 32) {
    const Lh = parseInt(inHex.substr(off, 8), 16) >>> 0;
    const Ll = parseInt(inHex.substr(off + 8, 8), 16) >>> 0;
    const Rh = parseInt(inHex.substr(off + 16, 8), 16) >>> 0;
    const Rl = parseInt(inHex.substr(off + 24, 8), 16) >>> 0;
    const [cl0, cl1, cr0, cr1] = seedCryptBlock(Lh, Ll, Rh, Rl, rks, decrypt);
    out += u32(cl0) + u32(cl1) + u32(cr0) + u32(cr1);
  }
  return out;
}
const seedEncode = (t, p) => seedCrypt(t, p, false);
const seedDecode = (t, p) => seedCrypt(t, p, true);

