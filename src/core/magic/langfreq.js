// ============================================================================
// 中文 UTF-8 字节级频率表（ZH）—— 语义同 EN（百分比 0-100，下标 = 字节值）。
//
// 数据性质：**基于「常用汉字文本以 UTF-8 编码后的字节直方图」的粗略估计**
// 非某单一权威语料的逐字节精确统计值（无公开的字节级中文频率权威表
// 故用「明确标注依据的合理估计」而非伪精确数据）。
//
// 构造依据：
// 1) 常用汉字 U+4E00-U+9FFF 以 UTF-8 编码为 3 字节：引导字节落在 0xE4-0xE9
// （对应 U+4xxx-U+9xxx），后两字节为 continuation（0x80-0xBF）。故 UTF-8
// 中文文本里 continuation 区（0x80-0xBF）约占全部字节的 2/3，引导区约 1/3。
// 2) 中文标点 / 全角字符（U+3000-U+303F、U+FF00-U+FFEF 等）引导字节为 0xE3/0xEF。
// 3) 真实中文文本常混入 ASCII（空格、数字、拉丁字母、半角标点），给 ASCII 区中低频。
//
// 用途：仅作 magic 打分时 chiSquareScore(observed, ZH) 的 expected 参数，与 EN 表
// 取 min（见 magic.js compositeScore）。中文正解在 EN 表下卡方极大（高频字节
// 0xE4-0xBF 在 EN 里期望≈0）、在 ZH 表下卡方小 → 取 min 后能排到候选前列。
// 数值为「使中英文卡方可区分」的相对分布，不做绝对统计断言。
// ============================================================================
function buildZH() {
  const z = new Array(256).fill(0.002); // 基线（防卡方除零，等价「罕见字节」期望）

 // ASCII 区：中文文本常混入的空白/数字/字母/半角标点，中低频
  z[0x0A] = 0.30; // \n
  z[0x0D] = 0.10; // \r
  z[0x20] = 1.80; // 空格
  for (let b = 0x30; b <= 0x39; b++) z[b] = 0.15; // 数字 0-9
  for (let b = 0x41; b <= 0x5A; b++) z[b] = 0.05; // 大写字母 A-Z
  for (let b = 0x61; b <= 0x7A; b++) z[b] = 0.08; // 小写字母 a-z
  for (const b of [0x2c, 0x2e, 0x3a, 0x3b, 0x21, 0x3f, 0x28, 0x29, 0x22, 0x27, 0x2d, 0x2f]) {
    z[b] = 0.10; // 半角标点 , . : ; ! ? ( ) " ' - /
  }

 // continuation 字节 0x80-0xBF：汉字/中文标点的后续字节，占比最高（约 2/3）
  for (let b = 0x80; b <= 0xbf; b++) z[b] = 0.90;

 // 2 字节引导 0xC2-0xDF（拉丁扩展/西里尔等）：中文文本罕见，低频
  for (let b = 0xc2; b <= 0xdf; b++) z[b] = 0.02;

 // 3 字节引导 0xE0-0xEF：汉字主要落在 E4-E9，中文标点/全角落在 E3/EF
  z[0xe3] = 1.50; // U+3000-U+3FFF（中文标点、注音符号等）
  z[0xe4] = 5.00; // U+4000-U+4FFF（含 U+4E00 起 CJK 常用字高频段）
  z[0xe5] = 6.00; // U+5000-U+5FFF
  z[0xe6] = 6.00; // U+6000-U+6FFF
  z[0xe7] = 5.00; // U+7000-U+7FFF
  z[0xe8] = 5.00; // U+8000-U+8FFF
  z[0xe9] = 4.00; // U+9000-U+9FFF
  z[0xea] = 0.30;
  z[0xeb] = 0.30;
  z[0xec] = 0.30;
  z[0xed] = 0.30;
  z[0xee] = 0.30;
  z[0xef] = 1.50; // U+F000-U+FFFF（含全角标点 U+FF00 等）

  return z;
}

export const ZH = buildZH();

if (ZH.length !== 256) {
  throw new Error(`langfreq.ZH length must be 256, got ${ZH.length}`);
}

export default { EN, ZH };
