/*
 * aria.js — ARIA 分组密码（cat:'modern'，双向）。
 *
 * 韩国标准 ARIA（KS X 1213 / RFC 5794），信创/国际赛题常见，128 位分组：
 *   - 轮数按密钥 128/192/256 = 12/14/16 轮；末轮额外一层密钥加（需 13/15/17 个轮密钥）。
 *   - 替换层 SL1/SL2 交替（SL2 = SL1 逆），扩散层 A 为对合（A(A(x))=x）。
 *   - 密钥调度：KL||KR 补零到 256 位 → 3 轮 Feistel 得 W0..W3 → 旋转组合得 ek1..ek17。
 *
 * 官方测试向量（RFC 5794 附录 A，已用 openssl 复现一致）：
 *   key=000102…0f  pt=00112233445566778899aabbccddeeff → d718fbd6ab644c739da95f3be6451778（128）
 *   key=…14151617                                 → 26449c1805dbe7aa25a468ce263a9e79（192）
 *   key=…1c1d1e1f                                 → f92bd7c79fb72e2f2b8f80c1972d24fc（256）
 *
 * 约定（与其它分组密码 op 一致）：encode=加密 decode=解密（明文/密文/密钥 hex，ECB 多块）；
 *   128 位分组 = 16 字节 = 32 hex，末块不足报错（ECB 不填充）。
 *
 * 红线：RFC 5794 原文实现不编造；S 盒/扩散层照表抄；交付前过官方向量。core 零 UI 依赖。
 */
