// 基础工具
// ============================================================
const XOR = (a, b) => { const r = new Uint8Array(16); for (let i = 0; i < 16; i++) r[i] = a[i] ^ b[i]; return r; };

function rotLeft(v, r) {
  r = ((r % 128) + 128) % 128;
  if (r === 0) return v.slice();
  const bs = r >> 3, bits = r & 7;
  const out = new Uint8Array(16);
  for (let i = 0; i < 16; i++) {
    const s = (i + bs) % 16;
    let val = v[s];
    if (bits) val = ((val << bits) | (v[(s + 1) % 16] >>> (8 - bits))) & 0xff;
    out[i] = val;
  }
  return out;
}
const rotRight = (v, r) => rotLeft(v, (128 - (r % 128)) % 128);

// 扩散层 A（对合）
function diffusionA(x) {
  const x0=x[0],x1=x[1],x2=x[2],x3=x[3],x4=x[4],x5=x[5],x6=x[6],x7=x[7],
        x8=x[8],x9=x[9],x10=x[10],x11=x[11],x12=x[12],x13=x[13],x14=x[14],x15=x[15];
  return Uint8Array.from([
    x3^x4^x6^x8^x9^x13^x14, x2^x5^x7^x8^x9^x12^x15,
    x1^x4^x6^x10^x11^x12^x15, x0^x5^x7^x10^x11^x13^x14,
    x0^x2^x5^x8^x11^x14^x15, x1^x3^x4^x9^x10^x14^x15,
    x0^x2^x7^x9^x10^x12^x13, x1^x3^x6^x8^x11^x12^x13,
    x0^x1^x4^x7^x10^x13^x15, x0^x1^x5^x6^x11^x12^x14,
    x2^x3^x5^x6^x8^x13^x15, x2^x3^x4^x7^x9^x12^x14,
    x1^x2^x6^x7^x9^x11^x12, x0^x3^x6^x7^x8^x10^x13,
    x0^x3^x4^x5^x9^x11^x14, x1^x2^x4^x5^x8^x10^x15,
  ]);
}

// 替换层：SL1/1 at byte index
const sl1At = (v, i) => (i % 4 === 0 ? SB1 : i % 4 === 1 ? SB2 : i % 4 === 2 ? SB3 : SB4)[v];
const sl2At = (v, i) => (i % 4 === 0 ? SB3 : i % 4 === 1 ? SB4 : i % 4 === 2 ? SB1 : SB2)[v];

// 轮函数：FO = A(SL1(D^rk))（odd=even param=false；实际用 SL1），FE = A(SL2(...))
// 这里 even=true=用SL2（FE），false=用SL1（FO）
function fRound(x, rk, even) {
  const t = new Uint8Array(16);
  for (let i = 0; i < 16; i++) t[i] = even ? sl2At(x[i] ^ rk[i], i) : sl1At(x[i] ^ rk[i], i);
  return diffusionA(t);
}

