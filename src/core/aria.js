const CK1 = Uint8Array.from([0x51,0x7c,0xc1,0xb7,0x27,0x22,0x0a,0x94,0xfe,0x13,0xab,0xe8,0xfa,0x9a,0x6e,0xe0]);
const CK2 = Uint8Array.from([0x6d,0xb1,0x4a,0xcc,0x9e,0x21,0xc8,0x20,0xff,0x28,0xb1,0xd5,0xef,0x5d,0xe2,0xb0]);
const CK3 = Uint8Array.from([0xdb,0x92,0x37,0x1d,0x21,0x26,0xe9,0x70,0x03,0x24,0x97,0x75,0x04,0xe8,0xc9,0x0e]);

function keysched(keyHex) {
  const c = keyHex.replace(/[^0-9a-fA-F]/g, "");
  if (![32, 48, 64].includes(c.length)) throw new Error("ARIA 密钥须为 128/192/256 位（32/48/64 hex）");
  const K = new Uint8Array(32);
  for (let i = 0; i < c.length; i += 2) K[i >> 1] = parseInt(c.substr(i, 2), 16);
  const KL = K.slice(0, 16);
  let KR;
  if (c.length === 32) KR = new Uint8Array(16); // 128 位 → KR=0
  else if (c.length === 48) { // 192 位：24 字节，补 8 个 0
    KR = new Uint8Array(16);
    for (let i = 0; i < 16; i++) KR[i] = (i < 8 ? K[16 + i] : 0);
  }
  else KR = K.slice(16, 32); // 256 位
  const ck = c.length === 32 ? [CK1, CK2, CK3] : c.length === 48 ? [CK2, CK3, CK1] : [CK3, CK1, CK2];
  const nRK = c.length === 32 ? 13 : c.length === 48 ? 15 : 17;
  const W0 = KL;
  const W1 = XOR(fRound(W0, ck[0], false), KR);
  const W2 = XOR(fRound(W1, ck[1], true), W0);
  const W3 = XOR(fRound(W2, ck[2], false), W1);
  const ek = [];
  ek.push(XOR(W0, rotRight(W1, 19)));
  ek.push(XOR(W1, rotRight(W2, 19)));
  ek.push(XOR(W2, rotRight(W3, 19)));
  ek.push(XOR(rotRight(W0, 19), W3));
  ek.push(XOR(W0, rotRight(W1, 31)));
  ek.push(XOR(W1, rotRight(W2, 31)));
  ek.push(XOR(W2, rotRight(W3, 31)));
  ek.push(XOR(rotRight(W0, 31), W3));
  ek.push(XOR(W0, rotLeft(W1, 61)));   // ek9  = W0 ^ (W1 <<< 61)
  ek.push(XOR(W1, rotLeft(W2, 61)));   // ek10
  ek.push(XOR(W2, rotLeft(W3, 61)));   // ek11
  ek.push(XOR(rotLeft(W0, 61), W3));   // ek12 = (W0 <<< 61) ^ W3
  if (nRK >= 13) ek.push(XOR(W0, rotLeft(W1, 31)));  // ek13
  if (nRK >= 14) ek.push(XOR(W1, rotLeft(W2, 31)));  // ek14
  if (nRK >= 15) ek.push(XOR(W2, rotLeft(W3, 31)));  // ek15
  if (nRK >= 16) ek.push(XOR(rotLeft(W0, 31), W3));  // ek16
  if (nRK >= 17) ek.push(XOR(W0, rotLeft(W1, 19)));  // ek17 = W0 ^ (W1 <<< 19)
  return { ek, rounds: nRK - 1 };
}

// ============================================================
// 加解密（n 轮，末轮 SL2）
// ============================================================
function encBlock(D, ek, n, decrypt) {
  // RFC：第 i 轮（i 从 1）使 ek_i；奇轮用 SL1（FO），偶轮用 SL2（FE）
  // 前 n-1 轮；末轮 C = SL2(P_{n-1} ^ ek_n) ^ ek_{n+1}
  let P = Uint8Array.from(D);
  for (let i = 1; i <= n - 1; i++) P = fRound(P, ek[i - 1], i % 2 === 0); // 偶轮用 FE
  // 注意：round 1 用 SL1（odd），即 even=false；round 2 用 SL2＝true。i%2===0 → i=2 SL2 true。i=1 false。✓
  const pre = XOR(P, ek[n - 1]);
  const s = new Uint8Array(16);
  for (let i = 0; i < 16; i++) s[i] = sl2At(pre[i], i);
  return XOR(s, ek[n]);
}

function decBlock(D, ek, n) {
  // 解密轮密钥：dk1 = ek_{n+1}；dk_i = A(ek_{n+2-i})，i=2..n；dk_{n+1} = ek_1
  const dk = [];
  dk.push(ek[n]);                     // dk1 = ek_{n+1}
  for (let i = n - 1; i >= 1; i--) dk.push(diffusionA(ek[i])); // dk2..dk_n = A(ek_n..ek_2)
  dk.push(ek[0]);                      // dk_{n+1} = ek_1（无需 A）
  return encBlock(D, dk, n);
}

const hexToBlock = (h) => { const b = new Uint8Array(16); for (let i = 0; i < 16; i++) b[i] = parseInt(h.substr(i * 2, 2), 16); return b; };
const blockToHex = (b) => { let s = ""; for (const x of b) s += x.toString(16).padStart(2, "0"); return s; };

function ariaCrypt(text, p, decrypt) {
  const keyHex = String((p && p.key) || "");
  const { ek, rounds } = keysched(keyHex);
  const inHex = String(text || "").replace(/[^0-9a-fA-F]/g, "");
  if (inHex.length === 0 || inHex.length % 32 !== 0) throw new Error("输入须为 16 字节（32 hex）的整数倍，ECB 不自动填充");
  let out = "";
  for (let off = 0; off < inHex.length; off += 32) {
    const block = hexToBlock(inHex.slice(off, off + 32));
    const res = decrypt ? decBlock(block, ek, rounds) : encBlock(block, ek, rounds);
    out += blockToHex(res);
  }
  return out;
}
const ariaEncode = (t, p) => ariaCrypt(t, p, false);
const ariaDecode = (t, p) => ariaCrypt(t, p, true);

