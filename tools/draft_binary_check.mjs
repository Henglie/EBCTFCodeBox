import assert from 'node:assert/strict';
import { encodeDraftFiles, decodeDraftFiles } from '../src/ui/draftBinary.js';
const bytes = Uint8Array.of(0, 255, 239, 187, 191, 10, 128);
const file = new File([bytes], 'image-原图.bin', { type: 'application/octet-stream', lastModified: 123456 });
const source = { file, original: file, empty: new Blob(), nested: [{ bytes: Uint8Array.of(3, 2, 1) }], label: 'metadata' };
source.self = source;
const encoded = await encodeDraftFiles(source);
assert(!(encoded.file instanceof Blob));
assert.deepEqual(encoded.file.bytes, bytes);
assert.equal(encoded.file.name, file.name);
assert.equal(encoded.file.lastModified, 123456);
assert.equal(encoded.file, encoded.original);
assert.equal(encoded.self, encoded);
assert.equal(source.file, file);
const restored = decodeDraftFiles(structuredClone(encoded));
assert(restored.file instanceof File);
assert.deepEqual(new Uint8Array(await restored.file.arrayBuffer()), bytes);
assert.equal(restored.file.name, file.name);
assert.equal(restored.file.type, file.type);
assert.equal(restored.file.lastModified, 123456);
assert.equal(restored.empty.size, 0);
assert.equal(restored.file, restored.original);
assert.equal(restored.self, restored);
assert.deepEqual(restored.nested[0].bytes, Uint8Array.of(3, 2, 1));
assert.equal(restored.label, 'metadata');
const keys = JSON.parse('{"__proto__":{"ordinary":"value"}}');
const roundtrip = decodeDraftFiles(await encodeDraftFiles(keys));
assert(Object.hasOwn(roundtrip, '__proto__'));
assert.equal(Object.getPrototypeOf(roundtrip), Object.prototype);
assert.equal(roundtrip.__proto__.ordinary, 'value');
